package mitsubishi

import (
	_ "embed"
	"encoding/binary"
	"fmt"
	"strings"
	"unicode/utf16"
)

// TextEncoding selects how data type 4 (text) registers are decoded.
type TextEncoding int

const (
	// TextAuto decodes each word as ASCII or Shift-JIS (CP932), picking
	// per word. This is what GOT text input writes by default, and plain
	// ASCII words come out byte-for-byte as before.
	TextAuto TextEncoding = iota
	// TextUnicode decodes each word as one UTF-16LE code unit (GOT
	// "Unicode" string devices). It must be chosen explicitly: a UTF-16
	// kanji such as 一 (U+4E00 = bytes 00 4E) is indistinguishable from
	// two ASCII bytes, so it cannot be auto-detected.
	TextUnicode
)

// ParseTextEncoding maps the TEXT_ENCODING setting to a TextEncoding.
// Empty, "auto", "ascii", "sjis" and "shift-jis" all mean TextAuto.
func ParseTextEncoding(s string) (TextEncoding, error) {
	switch strings.ToLower(strings.TrimSpace(s)) {
	case "", "auto", "ascii", "sjis", "shift-jis", "shift_jis", "shiftjis", "cp932":
		return TextAuto, nil
	case "unicode", "utf16", "utf-16", "utf16le", "utf-16le":
		return TextUnicode, nil
	default:
		return TextAuto, fmt.Errorf("unknown text encoding %q (use auto or unicode)", s)
	}
}

func (e TextEncoding) String() string {
	if e == TextUnicode {
		return "unicode"
	}
	return "auto"
}

// sjisTable is the CP932 double-byte → Unicode table generated by
// script/gen_sjis_table.py: 60 lead bytes × 188 trail slots, little-endian
// uint16 code points, 0 = unmapped.
//
//go:embed sjis_cp932.bin
var sjisTable []byte

func sjisLeadIndex(b byte) int {
	switch {
	case b >= 0x81 && b <= 0x9F:
		return int(b - 0x81)
	case b >= 0xE0 && b <= 0xFC:
		return int(b-0xE0) + 31
	}
	return -1
}

func sjisTrailIndex(b byte) int {
	switch {
	case b >= 0x40 && b <= 0x7E:
		return int(b - 0x40)
	case b >= 0x80 && b <= 0xFC:
		return int(b-0x80) + 63
	}
	return -1
}

// sjisRune decodes one Shift-JIS double-byte character, ok=false if the
// pair is not a mapped character.
func sjisRune(lead, trail byte) (rune, bool) {
	li, ti := sjisLeadIndex(lead), sjisTrailIndex(trail)
	if li < 0 || ti < 0 {
		return 0, false
	}
	i := (li*188 + ti) * 2
	cp := binary.LittleEndian.Uint16(sjisTable[i:])
	return rune(cp), cp != 0
}

// sjisSingle decodes a single-byte Shift-JIS character: ASCII or
// half-width katakana (0xA1-0xDF → U+FF61-U+FF9F).
func sjisSingle(b byte) (rune, bool) {
	switch {
	case b < 0x80:
		return rune(b), true
	case b >= 0xA1 && b <= 0xDF:
		return rune(0xFF61 + int(b) - 0xA1), true
	}
	return 0, false
}

// decodeTextWord decodes one 16-bit register (lo = low byte, which holds
// the first character in PLC memory; hi = high byte).
//
// Output order follows the original behaviour, which emits the high byte
// first ("AB" stored as lo='A' hi='B' comes out as "BA"); downstream
// consumers already account for that. A double-byte kanji fills the whole
// word, so it comes out as a single character with nothing to reorder.
func decodeTextWord(lo, hi byte, enc TextEncoding) string {
	if enc == TextUnicode {
		r := rune(uint16(lo) | uint16(hi)<<8)
		if utf16.IsSurrogate(r) {
			// Half of a surrogate pair; a lone word can't form the character.
			return string(rune(0xFFFD))
		}
		return string(r)
	}

	// Plain ASCII: unchanged from the original decoder.
	if lo < 0x80 && hi < 0x80 {
		return string([]byte{hi, lo})
	}

	// One full-width character (kanji, kana, full-width symbols).
	if r, ok := sjisRune(lo, hi); ok {
		return string(r)
	}

	// Two single-byte characters, e.g. half-width katakana or ASCII mixed
	// with half-width katakana. Keep the high-byte-first order.
	if rl, okl := sjisSingle(lo); okl {
		if rh, okh := sjisSingle(hi); okh {
			return string([]rune{rh, rl})
		}
	}

	// Not decodable as a whole word: usually a full-width character split
	// across two registers by a preceding half-width character. Emit the
	// decodable half and mark the other with U+FFFD rather than sending
	// invalid UTF-8.
	var b strings.Builder
	for _, x := range []byte{hi, lo} {
		if r, ok := sjisSingle(x); ok {
			b.WriteRune(r)
		} else {
			b.WriteRune(0xFFFD)
		}
	}
	return b.String()
}
